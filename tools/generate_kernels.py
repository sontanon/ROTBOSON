def _ccode(expr):
    # sympy ccode already emits M_PI and pow(); drop the redundant `1.0*`.
    return sp.ccode(expr, user_functions={})


def _expr_strings(jac):
    """Convert the 6x31 sympy Jacobian to 6x31 C strings (zero -> '0')."""
    out = []
    for row in jac:
        r = []
        for e in row:
            if e == 0:
                r.append("0")
            else:
                s = _ccode(e)
                s = s.replace("1.0*", "").replace("*(1.0", "*(")
                r.append(s)
        out.append(r)
    return out


