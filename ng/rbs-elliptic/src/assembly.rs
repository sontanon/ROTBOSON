#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn params_expose_the_omega_chain_rule() {
        let p = ProblemParams {
            l: 1,
            m: 1.0,
            xi: 0.0,
            q1: 1.0,
            q2: 1.0,
        };
        assert!((p.omega() - 0.5).abs() < 1e-15);
        assert!((p.dw_dxi() - 0.5).abs() < 1e-15);
        assert_eq!(DRIVER_RESCALE, -1.0);
    }
}
