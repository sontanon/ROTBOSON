//! Shared helpers for the rbs-io gates: the l=1 N=64 smoke snapshot.
//!
//! Source of truth: the vertical slice's parity fixture
//! (`ng/rbs-elliptic/tests/fixtures/l1_smoke_n64_solution.txt`) — the
//! six-field solve state already proven at C-oracle parity (SAN-62). The
//! HDF5 gate compares the Rust-written file against these values, so a
//! cross-crate fixture read is the point, not an accident.

#![allow(dead_code)] // shared between test binaries and the example

use std::path::{Path, PathBuf};

use rbs_io::hdf5::SnapshotAttrs;
use rbs_io::{FieldBlock, GridTopology, SeriesBlock};

/// The slice fixture: `ng/rbs-elliptic/tests/fixtures/…` relative to the
/// crate manifest (works from tests and examples alike).
pub fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(
        ["..", "rbs-elliptic", "tests", "fixtures", "l1_smoke_n64_solution.txt"]
            .iter()
            .collect::<PathBuf>(),
    )
}

/// The committed Rust-written HDF5 fixture (regenerated by
/// `examples/l1_smoke_snapshot.rs`; see its header).
pub fn rust_h5_fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join(["tests", "fixtures", "l1_smoke_n64_rust.h5"].iter().collect::<PathBuf>())
}

pub struct SmokeSnapshot {
    pub grid: GridTopology,
    pub fields: Vec<FieldBlock>,
    pub omega: f64,
}

impl SmokeSnapshot {
    /// The `w_f` series (the fixed-omega smoke pins w exactly).
    pub fn w_f(&self) -> SeriesBlock {
        SeriesBlock {
            name: "w_f".to_string(),
            values: vec![self.omega],
        }
    }
}

/// Parse the slice fixture into the six-field snapshot on the C's
/// cell-centered total grid (N=64 interior, order 4 → 2 ghost layers,
/// dr=dz=0.25, 68x68 totals).
pub fn load_smoke() -> SmokeSnapshot {
    let text = std::fs::read_to_string(fixture_path())
        .unwrap_or_else(|e| panic!("read {}: {e}", fixture_path().display()));
    let mut nr_total = 0usize;
    let mut nz_total = 0usize;
    let mut omega = 0.0f64;
    let mut fields: Vec<FieldBlock> = Vec::new();
    for line in text.lines() {
        let t = line.split_whitespace().collect::<Vec<_>>();
        if t.is_empty() || t[0].starts_with('#') {
            continue;
        }
        match t[0] {
            "nr_total" => nr_total = t[1].parse().expect("nr_total integer"),
            "nz_total" => nz_total = t[1].parse().expect("nz_total integer"),
            "omega" => omega = t[1].parse().expect("omega float"),
            "field" => fields.push(FieldBlock {
                name: t[1].to_string(),
                values: Vec::new(),
            }),
            _ => {
                let v: f64 = t[0].parse().expect("fixture value float");
                fields
                    .last_mut()
                    .expect("value follows a `field` header")
                    .values
                    .push(v);
            }
        }
    }
    assert_eq!(nr_total, 68, "smoke fixture grid");
    assert_eq!(nz_total, 68, "smoke fixture grid");
    assert_eq!(fields.len(), 6, "six fields in the smoke fixture");
    for f in &fields {
        assert_eq!(f.values.len(), 68 * 68, "field {} covers the grid", f.name);
    }
    let grid = GridTopology::centered(68, 68, 0.25, 0.25, 2);
    SmokeSnapshot { grid, fields, omega }
}

/// The smoke spec's root attributes: `configs/l1_smoke_ci.toml` (the
/// `l1_smoke_n64_hdf5.toml` twin minus outputFormat) at the fixture
/// generation protocol — epsilon=1e-12, maxNewtonIter=40, matching the
/// slice's deep-converged parity run. `w_idx = GNUM * dim = 6 * 4624`
/// (src/parser.c), fixedPhiR/Z are the context defaults the parser never
/// touches when fixedOmega=1.
///
/// `analysis_grid`/`analysis` stay `None`: the Rust snapshot carries no
/// `sph_*` datasets and no analysis has been computed on the NG side
/// yet (the writer emits those attributes only when a caller fills the
/// blocks — see SAN-65).
pub fn smoke_attrs(git_hash: &str, parfile: &str) -> SnapshotAttrs {
    use rbs_io::hdf5::{GridAttrs, ScalarFieldAttrs, SolverAttrs};
    SnapshotAttrs {
        git_hash: git_hash.to_string(),
        parfile: parfile.to_string(),
        grid: GridAttrs {
            dr: 0.25,
            dz: 0.25,
            nr_interior: 64,
            nz_interior: 64,
            nr_total: 68,
            nz_total: 68,
            dim: 4624,
            ghost: 2,
            order: 4,
        },
        field: ScalarFieldAttrs {
            l: 1,
            m: 1.0,
            psi0: 0.01,
            sigma_r: 4.0,
            sigma_z: 4.0,
            r_ext: 12.0,
            w0: 0.95,
            w_idx: 6 * 4624,
            fixed_phi: 0,
            fixed_phi_r: 4,
            fixed_phi_z: 4,
            fixed_omega: 1,
        },
        solver: SolverAttrs {
            solver_type: 1,
            local_solver: 1,
            epsilon: 1e-12,
            max_newton_iter: 40,
            lambda0: 1e-3,
            lambda_min: 1e-5,
            use_low_rank: 0,
            max_initial_guess_checks: 8,
            norm_f0_target: 1e-5,
        },
        ..SnapshotAttrs::default()
    }
}

/// Max |a - b| over a slice pair (NaN-safe: any NaN mismatch fails).
pub fn max_abs_diff(a: &[f64], b: &[f64]) -> f64 {
    assert_eq!(a.len(), b.len(), "compared slices have equal length");
    a.iter()
        .zip(b)
        .map(|(x, y)| {
            assert!(
                x.is_finite() && y.is_finite(),
                "field values must be finite"
            );
            (x - y).abs()
        })
        .fold(0.0, f64::max)
}

/// Path helper: `path` exists, or a panic naming it.
pub fn require(path: &Path) {
    assert!(path.exists(), "missing {}", path.display());
}
