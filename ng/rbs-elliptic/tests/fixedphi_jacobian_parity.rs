//! SAN-58 fixedPhi Jacobian parity: the assembled CSR vs the C
//! oracle's `csr_gen_jacobian` dump, entry by entry.
//!
//! The fixedOmega smoke gate (`l1_smoke_n64_parity.rs`) validates the
//! assembly only up to the fixed point it reaches: with the frequency
//! pinned, the omega row forces `du_omega = 0`, so the Jacobian's
//! OMEGA COLUMN never influences the solve. The fixedPhi mode is the
//! first consumer of that column (and of the psi-pin row), so this
//! gate pins the full matrix against the C directly:
//!
//! * the CSR pattern — row pointers and column indices — identical;
//! * every stored value identical to a few ULP (the C and the
//!   generated Rust evaluate the same expressions in different
//!   association orders, like the kernel-parity fixture);
//! * the omega row is the constraint: a single 1.0 at column
//!   `4*dim + IDX(fixedPhiR, fixedPhiZ)`;
//! * the omega column is live in the interior rows (nonzero entries
//!   scaled by `dw/dxi`);
//! * the total nnz equals `nnz_jacobian` of `src/csr.c`.
//!
//! Provenance (`tests/fixtures/fixedphi_jac_n6_*`): generated by a
//! scratch harness (kept out of the tree; the build recipe is below)
//! that constructs the C's `rb_context` for the spec echo committed
//! as `fixedphi_jac_n6_spec.txt` (`NrInterior` = `NzInterior` = 6, order
//! 4, l = 1, m = 1, fixedPhi at (2, 2), w0 = 0.95), fills a
//! deterministic smooth state whose GHOSTS satisfy the even-mirror
//! state convention, and calls `csr_gen_jacobian(ctx, A, u, 1)`
//! (the C's own print hook) to dump `a/ia/ja` plus the state:
//!
//! ```text
//! gcc -O2 -fopenmp -I src/compat -I src <main.c> \
//!   src/csr.c src/csr_grid_fill.c src/csr_symmetry.c src/csr_robin.c \
//!   src/csr_exp_decay.c src/csr_omega_constraint.c src/csr_vars.c \
//!   src/context.c src/log.c src/tools.c src/profile.c src/omega_calc.c \
//!   -lm -o jacdump
//! ```
//!
//! The even-ghost convention is load-bearing: the C's interior
//! kernels read the raw ghost cells (so the C's matrix is the exact
//! Jacobian only on the even manifold, where the symmetry rows pin
//! every real solve state), while this port emits the parity-folded
//! weights. The two agree exactly on the manifold — a non-even dump
//! state mismatches ~2k entries — so the fixture state mirrors the
//! ghosts, exactly like every state the Newton iteration produces.

use rbs_core::fields::FieldSet;
use rbs_core::grid::Grid2d;
use rbs_elliptic::assembly::{
    assemble_jacobian, nnz_jacobian_4th, JacobianPattern, ProblemParams, Workspace,
};
use rbs_elliptic::initial::SolveState;

/// Values agree to this relative tolerance (a few ULP; the C and the
/// generated kernels associate differently).
const TOLERANCE: f64 = 1e-13;

fn read_f64s(path: &str) -> Vec<f64> {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{path}: {e}"))
        .split_whitespace()
        .map(|v| v.parse().unwrap())
        .collect()
}

fn fixture(name: &str) -> String {
    format!(
        "{}/tests/fixtures/fixedphi_jac_n6_{name}",
        env!("CARGO_MANIFEST_DIR")
    )
}

#[test]
fn fixedphi_jacobian_matches_the_c_dump() {
    let a_c = read_f64s(&fixture("a.txt"));
    // 1-based CSR pointers and indices (BASE = 1 in the C).
    let ia_c: Vec<usize> = read_f64s(&fixture("ia.txt"))
        .iter()
        .map(|&v| v as usize)
        .collect();
    let ja_c: Vec<usize> = read_f64s(&fixture("ja.txt"))
        .iter()
        .map(|&v| (v as usize) - 1)
        .collect();
    let u_c = read_f64s(&fixture("u_dump.txt"));

    // The spec echo: NrInterior = NzInterior = 6 -> totals of 10.
    let grid = Grid2d::new(10, 10, 2, 0.25, 0.25);
    let dim = grid.dim();
    let nrows = 6 * dim + 1;
    assert_eq!(u_c.len(), nrows, "state dump length");

    let mut fields = FieldSet::zeros(&grid);
    for k in 0..6 {
        fields
            .field_mut(k)
            .copy_from_slice(&u_c[k * dim..(k + 1) * dim]);
    }
    let state = SolveState {
        fields,
        xi: u_c[6 * dim],
    };
    let params = ProblemParams {
        l: 1,
        m: 1.0,
        xi: u_c[6 * dim],
        q1: 1.0,
        q2: 1.0,
        fixed_phi: Some((2, 2)),
    };

    // Pattern first: nnz must be the C's counting formula, then the
    // row pointers and column indices identical.
    let pattern = JacobianPattern::build(&grid, &params);
    assert_eq!(
        pattern.nnz(),
        nnz_jacobian_4th(6, 6),
        "nnz vs the C formula"
    );
    assert_eq!(pattern.nnz(), a_c.len(), "nnz vs the C dump");

    let mut ws = Workspace::new(&grid);
    let jac = assemble_jacobian(&grid, &state.fields, &params, &mut ws);

    let row_ptrs: Vec<usize> = ia_c.iter().map(|&v| v - 1).collect();
    assert_eq!(row_ptrs.len(), jac.row_ptrs.len(), "ia length");
    assert_eq!(row_ptrs, jac.row_ptrs, "row pointers differ");
    assert_eq!(ja_c, jac.col_inds, "column indices differ");
    assert_eq!(a_c.len(), jac.vals.len(), "values length");

    // Values: identical to a few ULP everywhere.
    let mut worst = 0.0_f64;
    let mut worst_at = 0usize;
    let mut mismatches = 0usize;
    for (n, (&c, &r)) in a_c.iter().zip(&jac.vals).enumerate() {
        let d = (c - r).abs() / c.abs().max(1.0);
        if d > TOLERANCE {
            mismatches += 1;
        }
        if d > worst {
            worst = d;
            worst_at = n;
        }
    }
    assert_eq!(
        mismatches, 0,
        "{mismatches} Jacobian entries beyond {TOLERANCE}"
    );
    assert!(
        worst < TOLERANCE,
        "worst Jacobian deviation {worst:.3e} at entry {worst_at}"
    );

    // The omega row: the fixedPhi constraint — a single 1.0 at the
    // psi column of the pinned node (`csr_omega_constraint.c` with
    // g_num = 5, i = fixedPhiR, j = fixedPhiZ).
    let w_idx = 6 * dim;
    assert_eq!(
        jac.row_ptrs[w_idx + 1] - jac.row_ptrs[w_idx],
        1,
        "omega row nnz"
    );
    let pin_col = jac.col_inds[jac.row_ptrs[w_idx]];
    assert_eq!(pin_col, 4 * dim + grid.idx(2, 2), "pin column");
    assert!(
        (jac.vals[jac.row_ptrs[w_idx]] - 1.0).abs() < 1e-15,
        "pin value"
    );

    // The omega column is live in the interior rows (the fixedPhi
    // consumer): count its structural nonzeros.
    let mut live_rows = 0usize;
    for row in 0..w_idx {
        let cols = &jac.col_inds[jac.row_ptrs[row]..jac.row_ptrs[row + 1]];
        if cols.contains(&w_idx) {
            live_rows += 1;
        }
    }
    assert!(
        live_rows > 6 * 6,
        "the omega column must be live in the interior (found {live_rows} rows)"
    );

    // The pin row's value must be the ONLY entry the C puts there —
    // verified above via the dump equality; assert the residual's
    // omega row is identically zero to complete the constraint
    // semantics (`f[w_idx] = 0` of src/rhs.c).
    let f = rbs_elliptic::assembly::assemble_residual(&grid, &state.fields, &params, &mut ws);
    assert_eq!(f[w_idx], 0.0, "the omega constraint residual");
}
