//! Residual / Jacobian assembly over the grid — the SAN-62 port target.
//!
//! C cross-references:
//!
//! * residual: `src/rhs.c` sweeps the grid, computes the physical
//!   derivative arrays with the Fornberg stencils, calls `rhs_vars`
//!   (interior) or `rhs_bdry` (Robin rows at the outer boundary), and the
//!   driver passes `rescale = -1`;
//! * Jacobian: `src/csr_gen_jacobian` calls the `jacobian_*_variable_omega`
//!   stencil kernels, which scatter
//!   `aa[col] = sum_k coeff_k * jacobian_submatrix_g[k]` per stencil point
//!   (the `_emit_csr` rule of `tools/generate_kernels.py`) plus the omega
//!   column `dw_du(xi, m) * dF/dw`;
//! * omega constraint: `src/csr_omega_constraint.c` (the normalization
//!   row that closes the eigenvalue problem).
//!
//! The Rust kernels this assembly calls live in
//! [`crate::generated::kernels`] (generated by
//! `tools/generate_rust_kernels.py`).

use rbs_core::fields::FieldSet;
use rbs_core::grid::Grid2d;
use rbs_linalg::CsrMatrix;

/// Physical + discretization parameters of one elliptic solve.
#[derive(Debug, Clone, PartialEq)]
pub struct ProblemParams {
    /// Azimuthal number `l` (1..=6 in the oracle campaigns).
    pub l: i64,
    /// Scalar-field mass `m`.
    pub m: f64,
    /// Stored frequency parameter (the eigenvalue unknown actually solved
    /// for; the physical frequency is [`ProblemParams::omega`]).
    pub xi: f64,
    /// Regularization coefficient of the lambda equation (`Q1`; the C
    /// kernels hard-code `#define Q1 1.0`).
    pub q1: f64,
    /// Regularization coefficient (`Q2`; `#define Q2 1.0` in C).
    pub q2: f64,
}

impl ProblemParams {
    /// The physical frequency `w = omega_calc(xi, m)`.
    #[must_use]
    pub fn omega(&self) -> f64 {
        crate::omega::omega_calc(self.xi, self.m)
    }

    /// The omega-chain-rule factor `dw/dxi` used by the Jacobian's omega
    /// column.
    #[must_use]
    pub fn dw_dxi(&self) -> f64 {
        crate::omega::dw_dxi(self.xi, self.m)
    }
}

