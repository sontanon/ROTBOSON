# Which finite-difference quantities are materialized as locals (only those
# referenced by the Jacobian expressions; the rest are handled via the stencil
# coefficients in the CSR write-out).
FD_USED = {"dRu": (1, 2, 3, 5, 6), "dZu": (1, 2, 3, 5, 6), "dRRu": (1, 3)}

# Grid-function physical names, for the readability declarations.
GRID_NAME = {1: "u1", 2: "u2", 3: "u3", 4: "u4", 5: "u5", 6: "u6"}


def _param_name(g, dr_off, dz_off, dr_min, dz_min):
    return f"u{g}{dr_off - dr_min}{dz_off - dz_min}"


def _index_str(dr_off, dz_off):
    def off(axis, o):
        if o == 0:
            return axis
        return f"{axis} {'+' if o > 0 else '-'} {abs(o)}"

    return f"IDX({off('i', dr_off)}, {off('j', dz_off)})"


def _signature(fname, stencil, used_params=None):
    """Emit the function signature.  ``used_params`` is a set of parameter
    names referenced by the body; unused grid-value parameters are declared
    anonymous (no name) so the compiler does not warn about them."""
    dr_min = min(p[0][0] for p in stencil["points"])
    dz_min = min(p[0][1] for p in stencil["points"])
    used = used_params if used_params is not None else set()

    def named(name):
        return name if name in used else ""

    lines = [f"void {fname}("]
    lines.append("\tdouble *aa, MKL_INT *ia, MKL_INT *ja,")
    lines.append(
        "\tconst MKL_INT NrTotal, const MKL_INT NzTotal, const MKL_INT dim, const MKL_INT ghost,"
    )
    lines.append("\tconst MKL_INT i, const MKL_INT j, const double dr, const double dz,")
    lines.append("\tconst MKL_INT l, const double m, const double xi,")
    for g in range(1, 7):
        params = []
        for (dr_off, dz_off), _ in stencil["points"]:
            p = _param_name(g, dr_off, dz_off, dr_min, dz_min)
            nm = named(p)
            params.append(f"const double {nm}".rstrip())
        lines.append("\t" + ", ".join(params) + ",")
    lines.append("\tconst MKL_INT offset1, const MKL_INT offset2, const MKL_INT offset3,")
    lines.append("\tconst MKL_INT offset4, const MKL_INT offset5, const MKL_INT offset6)")
    return "\n".join(lines)


def _decl_block(stencil):
    """Grid-value + physical-variable declarations shared by every kernel."""
    dr_min = min(p[0][0] for p in stencil["points"])
    dz_min = min(p[0][1] for p in stencil["points"])
    center = {g: _param_name(g, 0, 0, dr_min, dz_min) for g in range(1, 7)}
    return "\n".join(
        [
            "\t// Grid values at the stencil centre (u1=log alpha, u2=beta,",
            "\t// u3=log h, u4=log a, u5=psi, u6=lambda).",
            f"\tdouble u1 = {center[1]};",
            f"\tdouble u2 = {center[2]};",
            f"\tdouble u3 = {center[3]};",
            f"\tdouble u4 = {center[4]};",
            f"\tdouble u5 = {center[5]};",
            f"\tdouble u6 = {center[6]};",
            "",
            "\t// Physical names for readability.",
            "\tdouble alpha = exp(u1);",
            "\tdouble h = exp(u3);",
            "\tdouble a = exp(u4);",
            "\tdouble psi = u5;",
            "\tdouble lambda = u6;",
            "",
            "\t// Coordinates and step ratios.",
            "\tdouble ri = (double)i + 0.5 - ghost;",
            "\tdouble r = ri * dr;",
            "\tdouble dzodr = dz / dr;",
            "\tdouble drodz = dr / dz;",
            "\tdouble dr2 = dr * dr;",
            "",
            "\t// Scalar field frequency and mass.",
            "\tdouble w = omega_calc(xi, m);",
            "\tdouble m2 = m * m;",
            "\tMKL_INT w_idx = GNUM * dim;",
            "",
            "\t// Scalar field short-hands (phi = r^l * psi).",
            "\tdouble rlm1 = (l == 1) ? 1.0 : pow(r, l - 1);",
            "\tdouble rl = rlm1 * r;",
            "\tdouble phior = rlm1 * psi;",
            "\tdouble phi = r * phior;",
            "\tdouble phi2or2 = phior * phior;",
            "\tdouble phi2 = phi * phi;",
            "\tdouble wplOmega = w + l * u2;",
            "",
            "\t// Squared variables.",
            "\tdouble alpha2 = alpha * alpha;",
            "\tdouble h2 = h * h;",
            "\tdouble a2 = a * a;",
        ]
    )


def _fd_block(stencil):
    """Emit the materialized finite-difference locals from the stencil."""
    dr_min = min(p[0][0] for p in stencil["points"])
    dz_min = min(p[0][1] for p in stencil["points"])
    lines = ["\t// Finite differences (step-scaled Fornberg stencils)."]
    for var, idxs in FD_USED.items():
        col = {"dRu": 1, "dZu": 2, "dRRu": 3}[var]
        for k in idxs:
            terms = []
            for (dr_off, dz_off), coeffs in stencil["points"]:
                c = coeffs[col]
                if c == "0.0":
                    continue
                p = _param_name(k, dr_off, dz_off, dr_min, dz_min)
                terms.append(f"{c} * {p}")
            lines.append(f"\tdouble {var}{k} = " + " + ".join(terms) + ";")
    return "\n".join(lines)


def _submatrix_decls():
    lines = [
        "\t// Jacobian submatrices: one 5-entry row per grid function,",
        "\t// plus the omega (frequency) entry.",
    ]
    for k in range(1, 7):
        lines.append(f"\tdouble jacobian_submatrix_{k}[5] = {{ 0.0 }};")
    lines.append("\tdouble jacobian_submatrix_w = 0.0;")
    return "\n".join(lines)


def _emit_rhs(jac_row, row_idx):
    """Emit the submatrix assignments for one residual equation (grid number)."""
    lines = []
    lines.append(f"\t// Jacobian of residual {row_idx} w.r.t. each grid function.")
    for g in range(1, 7):
        lines.append(f"\t//   submatrix {g} = [u, dRu, dZu, dRRu, dZZu].")
        for k in range(5):
            expr = jac_row[5 * (g - 1) + k]
            lines.append(f"\tjacobian_submatrix_{g}[{k}] = {expr};")
    w = jac_row[-1]
    lines.append("\t// Omega term (chain rule dw/dxi is applied at run time).")
    lines.append(f"\tjacobian_submatrix_w = dw_du(xi, m) * ({w});")
    return "\n".join(lines)


def _emit_csr(stencil, jac_row, row_idx):
    """Emit the CSR write-out for one residual equation."""
    off = row_idx  # offsetN variable is 1-based
    lines = []
    lines.append(f"\t// Row {row_idx - 1} * dim + IDX(i, j) starts at offset{off}.")
    lines.append(f"\tia[{row_idx - 1} * dim + IDX(i, j)] = BASE + offset{off};")
    lines.append("")
    lines.append("\t// Values.")
    n = 0
    for g in range(1, 7):
        for (_, _), coeffs in stencil["points"]:
            terms = []
            for k, c in enumerate(coeffs):
                if c == "0.0":
                    continue
                if jac_row[5 * (g - 1) + k] == "0":
                    continue
                terms.append(f"+{c}*jacobian_submatrix_{g}[{k}]")
            if terms:
                lines.append(f"\taa[offset{off} + {n:3d}] = " + "".join(terms) + ";")
                n += 1
    # omega term
    if jac_row[-1] != "0":
        lines.append(f"\taa[offset{off} + {n:3d}] = jacobian_submatrix_w;")
        n += 1
    lines.append("")
    lines.append("\t// Columns.")
    n = 0
    for g in range(1, 7):
        for (dr_off, dz_off), coeffs in stencil["points"]:
            terms = []
            for k, c in enumerate(coeffs):
                if c == "0.0":
                    continue
                if jac_row[5 * (g - 1) + k] == "0":
                    continue
                terms.append(f"+{c}*jacobian_submatrix_{g}[{k}]")
            if terms:
                lines.append(
                    f"\tja[offset{off} + {n:3d}] = BASE + {g - 1} * dim + "
                    f"{_index_str(dr_off, dz_off)};"
                )
                n += 1
    if jac_row[-1] != "0":
        lines.append(f"\tja[offset{off} + {n:3d}] = BASE + w_idx;")
    return "\n".join(lines)


def _function_body(fname, stencil, jac):
    body = ["\t(void)NrTotal;"]  # NrTotal is redundant (dim = NrTotal * NzTotal)
    body.append("")
    body.append(_decl_block(stencil))
    body.append("")
    body.append(_fd_block(stencil))
    body.append("")
    body.append(_submatrix_decls())
    for row_idx in range(1, 7):
        body.append("")
        body.append(f"\t// CSR CODE FOR GRID NUMBER {row_idx} (residual {row_idx - 1}).")
        body.append("")
        body.append(_emit_rhs(jac[row_idx - 1], row_idx))
        body.append("")
        body.append(_emit_csr(stencil, jac[row_idx - 1], row_idx))
    body.append("")
    body.append("\treturn;")
    body_text = "\n".join(body)
    # Parameters referenced by name in the body (grid values via the FD
    # stencils and the centre assignment).  Unused ones are declared
    # anonymous so the compiler does not warn (backlog item #7).
    used = set(re.findall(r"\bu\d\d\d\b", body_text))
    return _signature(fname, stencil, used) + "\n{\n" + body_text + "\n}"


